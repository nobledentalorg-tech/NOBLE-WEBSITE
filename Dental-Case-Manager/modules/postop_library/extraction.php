<h3 class="p-3">Post-Operative Care — Tooth Extraction</h3>
<div class="p-3">
  <h5>Do’s ✅</h5>
  <ul>
    <li>Bite gently on the gauze pad placed by your dentist for 30–45 minutes.</li>
    <li>Apply cold compress on the cheek for 10 minutes every hour on day 1.</li>
    <li>Eat soft, cool foods (curd rice, smoothies) for the first 24 hours.</li>
    <li>Take medications as prescribed.</li>
  </ul>

  <h5>Don’ts ❌</h5>
  <ul>
    <li>Do NOT spit, rinse, or use straws for 24 hours.</li>
    <li>Avoid smoking or alcohol for 48 hours.</li>
    <li>Do NOT disturb the blood clot or touch the socket.</li>
  </ul>

  <h5>When to Call Your Dentist ☎️</h5>
  <ul>
    <li>Persistent bleeding beyond 1 hour.</li>
    <li>Severe pain or swelling after 2 days.</li>
    <li>Fever, foul smell, or pus discharge.</li>
  </ul>

