<h3 class="p-3">Post-Operative Care — Dental Implant</h3>
<div class="p-3">
  <h5>Do’s ✅</h5>
  <ul>
    <li>Keep gentle pressure with gauze if mild bleeding occurs.</li>
    <li>Maintain oral hygiene with prescribed mouthwash (e.g. Chlorhexidine).</li>
    <li>Soft diet for 3 days; avoid chewing on the implant side.</li>
    <li>Attend scheduled follow-up visits for suture removal and check-up.</li>
  </ul>

  <h5>Don’ts ❌</h5>
  <ul>
    <li>Do NOT brush directly over the surgical area for 3 days.</li>
    <li>Avoid smoking or alcohol for 5 days.</li>
    <li>Do NOT lift the lip or disturb stitches.</li>
  </ul>

  <h5>Alert Dentist If 🚨</h5>
  <ul>
    <li>Severe pain unrelieved by medicines.</li>
    <li>Continuous bleeding or implant mobility.</li>
  </ul>

