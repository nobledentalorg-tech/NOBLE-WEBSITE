<h3 class="p-3">Post-Operative Care — Scaling / Cleaning</h3>
<div class="p-3">
  <h5>Do’s ✅</h5>
  <ul>
    <li>Brush gently with a soft-bristled brush twice daily.</li>
    <li>Rinse with warm salt water twice daily for 2 days.</li>
    <li>Drink plenty of water to stay hydrated.</li>
  </ul>

  <h5>Don’ts ❌</h5>
  <ul>
    <li>Avoid very hot, spicy, or hard foods for 24 hours.</li>
    <li>Do NOT skip brushing due to mild gum bleeding — it will subside.</li>
  </ul>

  <h5>Expected Sensations</h5>
  <ul>
    <li>Temporary sensitivity to cold — use a desensitizing toothpaste.</li>
  </ul>

