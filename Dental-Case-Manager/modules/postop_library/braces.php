<h3 class="p-3">Post-Operative Care — Braces / Orthodontic Treatment</h3>
<div class="p-3">
  <h5>Do’s ✅</h5>
  <ul>
    <li>Brush after every meal with an orthodontic brush and interdental cleaner.</li>
    <li>Use orthodontic wax on brackets causing irritation.</li>
    <li>Eat soft foods; cut fruits and vegetables into small pieces.</li>
  </ul>

  <h5>Don’ts ❌</h5>
  <ul>
    <li>Do NOT chew gum, sticky or hard food (nuts, popcorn, candy).</li>
    <li>Avoid biting with front teeth on apples / sandwiches.</li>
  </ul>

  <h5>Visit Dentist If</h5>
  <ul>
    <li>Wire pokes or bracket loosens.</li>
    <li>Severe pain persists beyond 2 days.</li>
  </ul>

